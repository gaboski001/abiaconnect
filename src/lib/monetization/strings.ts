export type StringKey = keyof typeof en

export function t(key: StringKey, vars: Record<string, string | number> = {}): string {
  return en[key].replace(/\{(\w+)\}/g, (_, k) => (k in vars ? String(vars[k]) : `{${k}}`))
}

/** Friendly text for the server's conversation/message rule errors, if any. */
export function messagingRuleText(message: string | undefined | null): string | null {
  const m = message ?? ''
  if (m.includes('awaiting_reply')) return en['chat.awaiting_reply']
  if (m.includes('messages_off')) return en['chat.messages_off']
  if (m.includes('connections_only')) return en['chat.connections_only']
  if (m.includes('match_required')) return en['chat.match_required']
  return null
}

export function formatMoney(minor: number, currency: string): string {
  try {
    return new Intl.NumberFormat(currency === 'NGN' ? 'en-NG' : 'en-US', {
      style: 'currency',
      currency,
      maximumFractionDigits: minor % 100 === 0 ? 0 : 2,
    }).format(minor / 100)
  } catch {
    return `${currency} ${(minor / 100).toFixed(2)}`
  }
}
